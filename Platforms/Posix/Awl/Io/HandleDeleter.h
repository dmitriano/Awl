#pragma once

#include "Awl/Io/Platform.h"

#include <cassert>

namespace awl::io
{
    struct HandleDeleter
    {
        void operator()(HANDLE h) const noexcept
        {
            int res = ::close(h);

            assert(res == 0);
            static_cast<void>(res);
        }
    };
}
