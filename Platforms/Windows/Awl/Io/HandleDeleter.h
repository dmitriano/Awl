#pragma once

#include "Awl/Io/Platform.h"

#include <cassert>

namespace awl::io
{
    struct HandleDeleter
    {
        void operator()(HANDLE h) const
        {
            BOOL bRes = ::CloseHandle(h);

            assert(bRes);
            static_cast<void>(bRes);
        }
    };
}
